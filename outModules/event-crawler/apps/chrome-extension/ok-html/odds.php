		function getOptions() {
			var data = localStorage.getItem('opbQsydOptions') || "{}";
			data = JSON.parse(data);
			if (JSON.stringify(data) == "{}") {
				data.options = {};
				data.options[matchid] = {};
			} else {
				if (data.options[matchid]) {
					var time = data.options[matchid].time || 0;
					var now = +(new Date());
					var gap = (now - time) / 1000 / 60 / 60;
					if (gap > 24) {
						data.options[matchid] = {}
						saveOptions(data);
					}
				} else {
					data.options[matchid] = {};
				}
			}
			return data;
		}


