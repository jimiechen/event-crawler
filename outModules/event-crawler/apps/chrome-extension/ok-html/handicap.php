                        panLine1.push(item === null ? null : arr[0])
                        panLine2.push(item === null ? null : arr[1])
                        panLine3.push(item === null ? null : arr[2])
                    })

                    return {
                        panLine1: panLine1,
                        panLine2: panLine2,
                        panLine3: panLine3
                    }
