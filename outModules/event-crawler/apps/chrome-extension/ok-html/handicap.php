                function handlePanBg(data, dataObj) {
                    var first = data[0] === null ? data[9] * -1 : data[0] * -1
                    var max = -dataObj.min_point
                    var min = -dataObj.max_point
                    var middle = 0

                    if (min === max) {
                        middle = min
                        min += -1
                        max += +1
                    } else if (min === first) {
                        middle = min
                        min = min - (max - middle)
                    } else if (max === first) {
                        middle = max
                        max = max + (middle - min)
                    } else {
                        middle = (min + max) / 2
                        var interval = middle - first
                        if (interval !== 0) {
                            middle = middle - interval
                            // 最大值和最小值 相差中间值为多少 以多的为标准
                            var maxInterval = max - middle
                            var minInterval = middle - min
                            if (maxInterval > minInterval) {
                                min = middle - maxInterval
                            } else {
                                max = middle + minInterval
                            }
                        }
                    }


                    var arr = [min, max, middle].sort(function (a, b) {return a-b})
                    var panLine1 = []
                    var panLine2 = []
                    var panLine3 = []

