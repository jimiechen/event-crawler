			var matchFilter = $(".jsMatchFilter");
			var addrFilter = $(".jsAddrFilter");
			var countFilter = $(".jsCountFilter");
			var filterInfo = historyFilterController[type];
			matchFilter.attr("type", type).find(".list>span").eq(filterInfo.match).removeClass("sed").addClass("sed");
